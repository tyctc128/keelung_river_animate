// 語音合成用的讀音修正（字幕仍顯示原字）
export function ttsText(s) {
  return s
    .replace(/林朝棨/g, '林朝啟')
    .replace(/焿子寮/g, '耕子寮')
    .replace(/侯硐/g, '侯洞')
    .replace(/1957 年/g, '一九五七年')
    .replace(/90 度/g, '九十度')
    .replace(/[「」]/g, '');
}
